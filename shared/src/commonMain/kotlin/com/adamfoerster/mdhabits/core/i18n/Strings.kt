/** Supported UI languages. Default is English. [displayName] is the endonym, shown untranslated
 *  in the language selector so users always recognize their own language. */
enum class Lang(val tag: String, val displayName: String) {
    EN("en", "English"),
    PT("pt", "Português"),
    ES("es", "Español"),
}

/** Resolves a BCP-47 tag (e.g. "pt-BR") to a supported [Lang], defaulting to English. */
fun langFromTag(tag: String?): Lang = when (tag?.lowercase()?.take(2)) {
    "pt" -> Lang.PT
    "es" -> Lang.ES
    else -> Lang.EN
}

